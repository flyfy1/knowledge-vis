#!/usr/bin/env node
'use strict';
/* Writes ../data.js from two public downloads (not shipped; kept in the scratch directory):
     node tools/make-data.cjs /tmp/agent-tasks/essays/a-fair-price-for-a-bet/data
   1. spx_options.json: Cboe delayed quotes for S&P 500 index options,
      https://cdn.cboe.com/api/global/delayed_quotes/options/_SPX.json (retrieved 2026-11-18; snapshot of the
      2026-11-17 close). Kept: about twenty strikes of two standard expiries, bid and ask of the call and the put, and
      Cboe's own implied volatility for cross-checking.
   2. fred_nasdaqcom.csv: NASDAQ Composite Index, daily close, FRED series NASDAQCOM,
      https://fred.stlouisfed.org/graph/fredgraph.csv?id=NASDAQCOM&cosd=1971-02-05&coed=2026-11-17 (retrieved
      2026-11-18). Kept: a histogram of daily log-returns in units of their standard deviation, exceedance counts, the
      five largest falls and rises, and two autocorrelation curves. No daily price is shipped.
   This is not a page.json generator (it needs the raw downloads), so --check does not rerun it. */
const fs = require('fs'), path = require('path');
const RAW = process.argv[2];
if (!RAW) { console.error('usage: node tools/make-data.cjs <dir with spx_options.json and fred_nasdaqcom.csv>'); process.exit(1); }

/* ── smile ── */
const j = JSON.parse(fs.readFileSync(path.join(RAW, 'spx_options.json'), 'utf8'));
const spot = j.data.close;
const QUOTE = Date.parse('2026-11-17T16:15:00-05:00'); // the index options close, New York
const EXP = { dec: ['SPX261218', '2026-12-18'], mar: ['SPX270319', '2027-03-19'] }; // AM-settled: 09:30 New York on the third Friday
const MONEY = [0.70, 0.75, 0.80, 0.85, 0.875, 0.90, 0.925, 0.95, 0.97, 0.98, 0.99, 1.0, 1.01, 1.02, 1.03, 1.05, 1.075, 1.10, 1.15];
const expiries = {};
for (const [key, [code, date]] of Object.entries(EXP)) {
  const m = {};
  for (const x of j.data.options) { const r = x.option.match(/^([A-Z]+)(\d{6})([CP])(\d{8})$/); if (!r || r[1] + r[2] !== code) continue; const K = +r[4] / 1000; (m[K] = m[K] || {})[r[3]] = x; }
  const Ks = Object.keys(m).map(Number).filter(K => K % 50 === 0 && m[K].C && m[K].P && m[K].C.bid > 0 && m[K].P.bid > 0).sort((a, b) => a - b);
  const picked = [...new Set(MONEY.map(t => Ks.reduce((b, K) => (Math.abs(K / spot - t) < Math.abs(b / spot - t) ? K : b))))];
  const settle = Date.parse(date + (date < '2027-03-14' ? 'T09:30:00-05:00' : 'T09:30:00-04:00'));
  expiries[key] = { code, date, T: +((settle - QUOTE) / (365 * 86400e3)).toFixed(6), rows: picked.map(K => ({ K, cb: m[K].C.bid, ca: m[K].C.ask, pb: m[K].P.bid, pa: m[K].P.ask, civ: m[K].C.iv, piv: m[K].P.iv })) };
}
const SMILE = { source: 'Cboe delayed quotes, S&P 500 index options (SPX)', url: 'https://cdn.cboe.com/api/global/delayed_quotes/options/_SPX.json', retrieved: '2026-11-18', asOf: '2026-11-17', spot, iv30: j.data.iv30, expiries };

/* ── returns ── */
const rows = fs.readFileSync(path.join(RAW, 'fred_nasdaqcom.csv'), 'utf8').trim().split('\n').slice(1).map(l => l.split(',')).filter(a => a[1] && isFinite(+a[1])).map(a => [a[0], +a[1]]);
const r = [], dates = [];
for (let i = 1; i < rows.length; i++) { r.push(Math.log(rows[i][1] / rows[i - 1][1])); dates.push(rows[i][0]); }
const n = r.length, mean = r.reduce((s, x) => s + x, 0) / n, sd = Math.sqrt(r.reduce((s, x) => s + (x - mean) * (x - mean), 0) / (n - 1));
const z = r.map(x => (x - mean) / sd);
const kurt = z.reduce((s, x) => s + x ** 4, 0) / n;
const W = 0.5, LO = -12, NB = 48, hist = new Array(NB).fill(0);
for (const x of z) hist[Math.min(NB - 1, Math.max(0, Math.floor((x - LO) / W)))]++;
const exceed = {}; for (let k = 2; k <= 10; k += 0.5) exceed[k.toFixed(1)] = z.filter(x => Math.abs(x) >= k).length;
const order = r.map((x, i) => i).sort((a, b) => r[a] - r[b]);
const day = i => ({ date: dates[i], pct: +((Math.exp(r[i]) - 1) * 100).toFixed(2), z: +z[i].toFixed(2) });
const acf = (a, L) => { const m = a.reduce((s, x) => s + x, 0) / a.length, v = a.reduce((s, x) => s + (x - m) * (x - m), 0); const o = []; for (let l = 1; l <= L; l++) { let c = 0; for (let i = l; i < a.length; i++) c += (a[i] - m) * (a[i - l] - m); o.push(+(c / v).toFixed(4)); } return o; };
const i87 = dates.indexOf('1987-10-19');
const years = (Date.parse(dates[n - 1]) - Date.parse(rows[0][0])) / (365.25 * 86400e3);
const RETURNS = { source: 'NASDAQ Composite Index, daily close (FRED series NASDAQCOM)', url: 'https://fred.stlouisfed.org/series/NASDAQCOM', retrieved: '2026-11-18', from: rows[0][0], to: dates[n - 1],
  n, mean: +mean.toPrecision(6), sd: +sd.toPrecision(6), perYear: +(n / years).toFixed(2), kurtosis: +kurt.toFixed(2), binLo: LO, binW: W, hist, exceed,
  worst: order.slice(0, 5).map(day), best: order.slice(-5).reverse().map(day), oct19: { log: +r[i87].toPrecision(6), pct: +((Math.exp(r[i87]) - 1) * 100).toFixed(2) },
  acfAbs: acf(r.map(Math.abs), 60), acfRaw: acf(r, 60) };

const body = `/* GENERATED by tools/make-data.cjs from two public downloads; do not edit. Sources, URLs and retrieval dates are in
   the SMILE and RETURNS objects below and in BRIEF.md. Small extracts only: no daily prices are shipped.
   UMD: window.FairBetData in the browser, module.exports in node. */
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.FairBetData = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  'use strict';
  const SMILE = ${JSON.stringify(SMILE)};
  const RETURNS = ${JSON.stringify(RETURNS)};
  return { SMILE, RETURNS };
});
`;
fs.writeFileSync(path.join(__dirname, '..', 'data.js'), body);
console.log(`data.js: ${body.length} bytes; smile ${Object.values(expiries).map(e => e.code + ' ' + e.rows.length + ' strikes T=' + e.T).join(', ')}; returns n=${n} sd=${sd.toFixed(5)} kurtosis=${kurt.toFixed(1)} from ${rows[0][0]} to ${dates[n - 1]}`);
console.log('worst', JSON.stringify(RETURNS.worst), 'exceed', JSON.stringify(exceed));
