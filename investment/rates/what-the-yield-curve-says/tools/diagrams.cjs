#!/usr/bin/env node
'use strict';
/* Writes the static diagrams figures/dg-*.html (inline SVG, labels by data-i18n key; strings live in content.*.md).
   Shapes are drawn from models.js / data.js where the caption says the scale is real. Run: node tools/diagrams.cjs */
const fs = require('fs'), path = require('path');
const M = require('../models.js'), D = M.DATA;
const OUT = path.join(__dirname, '..', 'figures');
const HEAD = '<!-- GENERATED by tools/diagrams.cjs (page.json generators); edit tools/diagrams.cjs and rerun, do not edit this file. -->\n';
const r1 = x => Math.round(x * 10) / 10;
const C = { gold: '#e9b949', cyan: '#63c7e6', red: '#f07a6d', green: '#7ad6a0', violet: '#b39dfb', line: '#2b3242', mute: '#a3aab8', dim: '#3a4254' };
function T(key, x, y, o) { o = o || {}; return `<text data-i18n="${key}" x="${r1(x)}" y="${r1(y)}" font-size="${o.fs || 14}"${o.a ? ` text-anchor="${o.a}"` : ''}${o.c ? ` class="${o.c}"` : ''}></text>`; }
function N(txt, x, y, o) { o = o || {}; return `<text x="${r1(x)}" y="${r1(y)}" font-size="${o.fs || 14}"${o.a ? ` text-anchor="${o.a}"` : ''} class="mono${o.c ? ' ' + o.c : ''}">${txt}</text>`; }
const rect = (x, y, w, h, fill, o) => `<rect x="${r1(x)}" y="${r1(y)}" width="${r1(Math.max(0, w))}" height="${r1(Math.max(0, h))}" rx="${(o && o.rx) || 2}" fill="${fill}"${o && o.op ? ` fill-opacity="${o.op}"` : ''}/>`;
const ln = (x1, y1, x2, y2, col, o) => `<line x1="${r1(x1)}" y1="${r1(y1)}" x2="${r1(x2)}" y2="${r1(y2)}" stroke="${col}" stroke-width="${(o && o.w) || 1.5}"${o && o.dash ? ` stroke-dasharray="${o.dash}"` : ''}${o && o.arrow ? ' marker-end="url(#ah' + o.arrow + ')"' : ''}/>`;
const poly = (pts, col, w, dash) => `<polyline fill="none" stroke="${col}" stroke-width="${w || 2}" stroke-linejoin="round"${dash ? ` stroke-dasharray="${dash}"` : ''} points="${pts.map(p => r1(p[0]) + ',' + r1(p[1])).join(' ')}"/>`;
const defs = id => `<defs><marker id="ah${id}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="${C.mute}"/></marker></defs>`;
function svg(name, h, body) {
  return HEAD + `<figure class="dia" id="${name}">\n  <svg viewBox="0 0 360 ${h}" role="img" data-i18n-aria="dg.${name.slice(3)}.aria">${defs(name.slice(3))}\n${body}\n  </svg>\n  <figcaption data-i18n-html="dg.${name.slice(3)}.cap"></figcaption>\n</figure>\n`;
}
const files = {};

/* dg-strips (ch1): a 5-year coupon bond is five zero-coupon bonds */
{
  const k = 'dg.strips', x0 = 40, dx = 62, base1 = 120, base2 = 260; let b = '';
  b += T(k + '.top', 8, 22, { c: 'g' });
  for (let t = 1; t <= 5; t++) { const x = x0 + (t - 1) * dx, h = t === 5 ? 80 : 18; b += rect(x, base1 - h, 34, h, C.gold, { op: 0.85 }); b += N(String(t), x + 17, base1 + 18, { a: 'middle', c: 'm' }); }
  b += ln(20, base1 + 2, 345, base1 + 2, C.line);
  b += ln(180, base1 + 28, 180, base1 + 60, C.mute, { arrow: 'strips' }); b += T(k + '.split', 192, base1 + 50, { c: 'm' });
  b += T(k + '.bot', 8, base1 + 84, { c: 'c' });
  for (let t = 1; t <= 5; t++) { const x = x0 + (t - 1) * dx, h = t === 5 ? 80 : 18; b += rect(x, base2 - h, 34, h, C.cyan, { op: 0.8 }); b += N('z' + String.fromCharCode(0x2080 + t), x + 17, base2 + 20, { a: 'middle', c: 'c' }); }
  b += ln(20, base2 + 2, 345, base2 + 2, C.line);
  b += T(k + '.yrs', 345, base2 + 34, { a: 'end', c: 'm' });
  files['dg-strips'] = svg('dg-strips', 300, b);
}

/* dg-fwd (ch2): two routes from today to t2 */
{
  const k = 'dg.fwd', X0 = 30, X1 = 160, X2 = 330, yA = 70, yB = 170; let b = '';
  b += ln(X0, 230, X2, 230, C.line); [[X0, '0'], [X1, 't₁'], [X2, 't₂']].forEach(([x, s]) => { b += ln(x, 225, x, 235, C.mute); b += N(s, x, 252, { a: 'middle', c: 'm' }); });
  b += ln(X0, yA, X2 - 4, yA, C.cyan, { w: 2.5, arrow: 'fwd' }); b += T(k + '.a', X0, yA - 14, { c: 'c' }); b += N('e^(z₂·t₂)', X2, yA + 22, { a: 'end', c: 'c' });
  b += ln(X0, yB, X1 - 4, yB, C.cyan, { w: 2.5, arrow: 'fwd' }); b += ln(X1, yB, X2 - 4, yB, C.violet, { w: 2.5, arrow: 'fwd' });
  b += T(k + '.b1', X0, yB - 14, { c: 'c' }); b += T(k + '.b2', X1 + 6, yB - 14, { c: 'v' });
  b += N('e^(z₁·t₁)', X1 - 6, yB + 22, { a: 'end', c: 'c' }); b += N('e^(f·(t₂−t₁))', X2, yB + 22, { a: 'end', c: 'v' });
  b += T(k + '.eq', 180, 285, { a: 'middle', c: 'g' });
  files['dg-fwd'] = svg('dg-fwd', 300, b);
}

/* dg-stack (ch3): yield = average expected short rate + term premium, from the model (preset "cuts", TP10 = 0.8) */
{
  const k = 'dg.stack', B = M.build(M.PATHS.cuts.map(v => v / 100), 0.008), mats = [1, 2, 3, 5, 7, 10];
  const Y = v => 230 - v * 100 / 0.06 * 0.32 * 10 / 10, x0 = 46, w = 34, dx = 50; let b = '';
  // scale: 0..6 % over 0..192 px
  const yy = v => 230 - v / 0.06 * 192;
  mats.forEach((n, i) => { const x = x0 + i * dx, e = B.exp[n - 1], tp = B.tp[n - 1]; b += rect(x, yy(e), w, 230 - yy(e), C.cyan, { op: 0.75, rx: 1 }); b += rect(x, yy(e + tp), w, yy(e) - yy(e + tp), C.violet, { op: 0.9, rx: 1 }); b += N(String(n), x + w / 2, 250, { a: 'middle', c: 'm' }); });
  [0, 2, 4, 6].forEach(v => { b += N(String(v), 34, yy(v / 100) + 5, { a: 'end', c: 'm', fs: 14 }); b += ln(38, yy(v / 100), 350, yy(v / 100), C.line, { w: 0.6 }); });
  b += T(k + '.exp', 46, 286, { c: 'c' }); b += T(k + '.tp', 46, 306, { c: 'v' });
  b += T(k + '.x', 350, 270, { a: 'end', c: 'm' }); b += T(k + '.y', 8, 22, { c: 'm' });
  void Y;
  files['dg-stack'] = svg('dg-stack', 318, b);
}

/* dg-seesaw (ch6): present values of a 10-year 4 % bond at 4 % balance at its Macaulay duration */
{
  const k = 'dg.seesaw', bd = M.bond(0.04, 10, 0.04), X = t => 26 + t * 31, beam = 170; let b = '';
  b += ln(X(0), beam, X(10.3), beam, C.mute, { w: 3 });
  for (let t = 1; t <= 10; t++) { const cf = 4 + (t === 10 ? 100 : 0), pv = cf / Math.pow(1.04, t), h = pv * 1.25; b += rect(X(t) - 10, beam - 2 - h, 20, h, C.gold, { op: 0.85 }); b += N(String(t), X(t), beam + 22, { a: 'middle', c: 'm', fs: 14 }); }
  const fx = X(bd.mac); b += ln(fx, beam + 2, fx, beam + 30, C.cyan, { dash: '3 3', w: 1.2 });
  b += `<path d="M${r1(fx)},${beam + 30} L${r1(fx - 14)},${beam + 58} L${r1(fx + 14)},${beam + 58} z" fill="${C.cyan}"/>`;
  b += T(k + '.pivot', fx - 20, beam + 80, { a: 'middle', c: 'c' });
  b += T(k + '.bar', 8, 22, { c: 'g' }); b += T(k + '.x', 350, beam + 104, { a: 'end', c: 'm' });
  files['dg-seesaw'] = svg('dg-seesaw', 284, b);
}

/* dg-barbell (ch7): the same duration, two ways (schematic widths ∝ present value; default lab values) */
{
  const k = 'dg.barbell', pf = M.immunise(7, 100, 2, 15, 0.045), X = t => 20 + t * 21; let b = '';
  const row = (y, legs, col) => legs.forEach(l => { const h = l.pv / pf.PVL * 60; b += rect(X(l.t) - 9, y - h, 18, h, col, { op: 0.85 }); });
  b += ln(X(0), 100, X(16), 100, C.line); row(100, pf.bullet, C.cyan); b += T(k + '.bullet', 8, 22, { c: 'c' });
  b += ln(X(0), 210, X(16), 210, C.line); row(210, pf.barbell, C.gold); b += T(k + '.barbell', 8, 132, { c: 'g' });
  [2, 7, 15].forEach(t => { b += N(String(t), X(t), 228, { a: 'middle', c: 'm', fs: 14 }); b += N(String(t), X(t), 118, { a: 'middle', c: 'm', fs: 14 }); });
  b += ln(X(7), 30, X(7), 214, C.red, { dash: '4 4', w: 1.2 }); b += T(k + '.liab', X(7) + 8, 250, { c: 'r' });
  b += T(k + '.x', 350, 270, { a: 'end', c: 'm' });
  files['dg-barbell'] = svg('dg-barbell', 280, b);
}

/* dg-shapes (ch8): first three principal components of monthly changes in ACM zero yields (real loadings) */
{
  const k = 'dg.shapes', P = D.pca, X = n => 40 + (n - 1) * 32, Y = v => 130 - v * 150; let b = '';
  b += ln(X(1), Y(0), X(10), Y(0), C.line); [1, 2, 5, 10].forEach(n => { b += N(String(n), X(n), 250, { a: 'middle', c: 'm', fs: 14 }); });
  const cols = [C.gold, C.cyan, C.violet], lab = ['l', 's', 'c'];
  P.load.forEach((L, i) => { b += poly(L.map((v, j) => [X(j + 1), Y(v)]), cols[i], 2.5); });
  b += T(k + '.l', 8, 22, { c: 'g' }); b += T(k + '.s', 8, 42, { c: 'c' }); b += T(k + '.c', 8, 62, { c: 'v' });
  b += T(k + '.x', 350, 270, { a: 'end', c: 'm' });
  void lab;
  files['dg-shapes'] = svg('dg-shapes', 280, b);
}

/* dg-credit (ch10): one year of a defaultable bond: survive or default and recover */
{
  const k = 'dg.credit'; let b = '';
  b += rect(14, 120, 86, 44, '#1a1f2b', { rx: 8 }); b += T(k + '.now', 57, 147, { a: 'middle' });
  b += ln(100, 135, 196, 64, C.green, { arrow: 'credit' }); b += ln(100, 150, 196, 216, C.red, { arrow: 'credit' });
  b += T(k + '.surv', 140, 86, { a: 'middle', c: 'n' }); b += T(k + '.def', 140, 210, { a: 'middle', c: 'r' });
  b += rect(200, 40, 150, 48, '#1a1f2b', { rx: 8 }); b += T(k + '.full', 275, 69, { a: 'middle', c: 'n' });
  b += rect(200, 192, 150, 48, '#1a1f2b', { rx: 8 }); b += T(k + '.rec', 275, 221, { a: 'middle', c: 'r' });
  b += T(k + '.eq', 180, 280, { a: 'middle', c: 'g' });
  files['dg-credit'] = svg('dg-credit', 296, b);
}

/* dg-ladder (ch11): S&P average 5-year cumulative default rate by rating, 1981–2024 (real) */
{
  const k = 'dg.ladder', R = ['AAA', 'AA', 'A', 'BBB', 'BB', 'B', 'CCC'], W = v => v / 50 * 200; let b = '';
  R.forEach((g, i) => { const y = 34 + i * 32, v = D.spg.cum[g][1], col = i < 4 ? C.cyan : C.gold; b += N(g, 54, y + 16, { a: 'end' }); b += rect(64, y + 2, Math.max(2, W(v)), 20, col, { op: 0.85 }); b += N(v.toFixed(2) + '%', 70 + Math.max(2, W(v)), y + 17, { c: 'm', fs: 14 }); });
  const yl = 34 + 4 * 32 - 5; b += ln(10, yl, 350, yl, C.red, { dash: '5 4', w: 1.3 });
  b += T(k + '.ig', 350, yl - 8, { a: 'end', c: 'c' }); b += T(k + '.hy', 350, yl + 18, { a: 'end', c: 'g' });
  b += T(k + '.x', 8, 18, { c: 'm' });
  files['dg-ladder'] = svg('dg-ladder', 270, b);
}

for (const [n, s] of Object.entries(files)) fs.writeFileSync(path.join(OUT, n + '.html'), s);
console.log('wrote', Object.keys(files).length, 'diagrams');
