'use strict';
const assert=require('node:assert/strict');
const api=require('../app.js');
const base=api.baseline();
assert(Math.abs(base.q-(base.demandIntercept-base.demandSlope*base.p))<1e-9,'Qd must equal equilibrium quantity');
assert(Math.abs(base.q-(base.supplyIntercept+base.supplySlope*base.p))<1e-9,'Qs must equal equilibrium quantity');
const taxed=api.marketState({tax:20});
assert(taxed.q<base.q,'a positive tax lowers quantity');
assert(taxed.buyerPrice>taxed.sellerPrice,'tax creates a buyer/seller wedge');
assert(api.deadweightLoss(base,taxed)>0,'tax creates deadweight loss');
const subsidized=api.marketState({subsidy:20});
assert(subsidized.q>base.q,'a subsidy raises quantity');
assert(subsidized.sellerPrice>subsidized.buyerPrice,'subsidy reverses the wedge');
const elastic=api.marketState({demandSlope:.3,tax:12});
const inelastic=api.marketState({demandSlope:1.4,tax:12});
assert(api.elasticityAt(elastic).demand<0&&api.elasticityAt(inelastic).demand<0,'demand point elasticity is negative');
assert(Math.abs(api.elasticityAt(elastic).demand)!==Math.abs(api.elasticityAt(inelastic).demand),'point elasticity changes with slope and crossing position');
const ss=api.surplusAt(base);
assert(ss.consumerSurplus>0&&ss.producerSurplus>0&&ss.totalSurplus===ss.consumerSurplus+ss.producerSurplus,'surplus areas add');
console.log('supply-demand core ok');
