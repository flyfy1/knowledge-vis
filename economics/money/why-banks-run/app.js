/* chart helpers */
function frame(w, h, m, x0, x1, y0, y1) {
  const L = m[3], R = w - m[1], T = m[0], B = h - m[2];
  return { L, R, T, B, X: x => L + (R - L) * (x - x0) / (x1 - x0 || 1), Y: y => B - (B - T) * (y - y0) / (y1 - y0 || 1) };
}
function niceStep(span, n) {
  const raw = span / n, p = Math.pow(10, Math.floor(Math.log10(raw))), f = raw / p;
  return (f < 1.5 ? 1 : f < 3 ? 2 : f < 7 ? 5 : 10) * p;
}
function axes(c, F, y0, y1, opts = {}) {
  const st = niceStep(y1 - y0, opts.n || 4);
  c.strokeStyle = C.grid; c.lineWidth = 1; c.fillStyle = C.mute; c.textAlign = 'right';
  for (let v = Math.ceil(y0 / st) * st; v <= y1 + 1e-9; v += st) {
    const y = F.Y(v); c.beginPath(); c.moveTo(F.L, y); c.lineTo(F.R, y); c.stroke();
    c.fillText(fmt(v, st < 1 ? 1 : 0), F.L - 6, y);
  }
  c.strokeStyle = C.axis; c.beginPath(); c.moveTo(F.L, F.T); c.lineTo(F.L, F.B); c.lineTo(F.R, F.B); c.stroke();
}
function xTicks(c, F, vals, f) {
  c.fillStyle = C.mute; c.textAlign = 'center'; c.textBaseline = 'top';
  vals.forEach(v => c.fillText(f ? f(v) : String(v), F.X(v), F.B + 5));
  c.textBaseline = 'middle';
}
function line(c, pts, color, w = 2.5, dash) {
  c.strokeStyle = color; c.lineWidth = w; c.setLineDash(dash || []); c.beginPath();
  pts.forEach(([x, y], i) => (i ? c.lineTo(x, y) : c.moveTo(x, y))); c.stroke(); c.setLineDash([]);
}
function label(c, s, x, y, color, align) { c.fillStyle = color || C.mute; c.textAlign = align || 'left'; c.fillText(s, x, y); }
const narrow = w => w < 420;
const bn = (x, d) => t('u.bn', { v: fmt(x, d == null ? 1 : d) });

/* horizontal stacked bar: segs = [[value, colour], …], scaled by X */
function hbar(c, X, y, h, segs, x0) {
  let acc = x0 || 0;
  for (const [v, col] of segs) { if (v > 0) { c.fillStyle = col; c.fillRect(X(acc), y, X(acc + v) - X(acc), h); } acc += v; }
}

