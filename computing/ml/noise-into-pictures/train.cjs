'use strict';
// Trains every network the page uses and writes weights.js (base64 float32, loaded by the page as window.NOISE_WEIGHTS).
// Deterministic: the same seeds give the same weights on the same Node version.
// Run from the repo root:  node computing/ml/noise-into-pictures/train.cjs [--out <file>] [--only eps,fm,…] [--steps N]
// Takes several minutes. tests/models.cjs checks the shipped weights; `node tests/models.cjs --retrain` re-runs this
// script into a scratch file and compares it with weights.js byte for byte.
//
// Networks (all: 10 inputs → 48 → 48 → 2, SiLU, Adam, cosine learning-rate decay; see models.js):
//   eps      ε-prediction on the spiral (DDPM loss, Ho et al. 2020 eq. 14), fresh data every batch
//   fm       velocity prediction on the spiral, linear path (flow matching, Lipman et al. 2023; rectified flow, Liu et al. 2023)
//   reflow   velocity prediction on fixed pairs (z, x₁) where x₁ is z carried by the exact flow of `fm`'s target field
//            (one "reflow" / 2-rectified flow step, Liu et al. 2023), using the exact field in place of a trained 1-rectified flow
//   memo16, memo128, memo1024   ε-prediction trained only on a fixed training set of that many spiral points
const fs = require('fs'), path = require('path');
const M = require('./models.js');
const args = process.argv.slice(2);
const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
const out = opt('--out', path.join(__dirname, 'weights.js'));
const only = opt('--only', null), STEPS = +opt('--steps', 60000);
const S = M.SPIRAL;

const PLAN = {
  eps: { kind: 'eps', seed: 11, data: (r, pt) => { const s = M.sampleMix(S, 1, r); pt[0] = s[0]; pt[1] = s[1]; } },
  fm: { kind: 'fm', seed: 12, data: (r, pt) => { const s = M.sampleMix(S, 1, r); pt[0] = s[0]; pt[1] = s[1]; } },
  reflow: { kind: 'reflow', seed: 13, pairs: 20000 }
};
for (const n of M.MEMO.sizes) {
  const set = M.trainingSet(n, M.MEMO.seed);
  PLAN['memo' + n] = { kind: 'eps', seed: 20 + n, data: (r, pt) => { const i = Math.floor(r.u() * n); pt[0] = set[2 * i]; pt[1] = set[2 * i + 1]; } };
}

function reflowPairs(n, seed) {
  const r = M.rng(seed), z = new Float64Array(2 * n);
  for (let i = 0; i < z.length; i++) z[i] = r.n();
  const x1 = M.fm.rk4(M.fm.velFn(S), Float64Array.from(z), 200);
  return { z, x1, n };
}

const weights = {};
if (fs.existsSync(out)) { try { const ctx = {}; new Function('window', fs.readFileSync(out, 'utf8'))(ctx); Object.assign(weights, ctx.NOISE_WEIGHTS || {}); } catch (e) { /* start fresh */ } }
for (const [name, p] of Object.entries(PLAN)) {
  if (only && !only.split(',').includes(name)) continue;
  const t0 = Date.now(), o = { steps: STEPS, batch: 256, seed: p.seed, lr: 3e-3, lrEnd: 5e-5, data: p.data };
  if (p.kind === 'reflow') { const P = reflowPairs(p.pairs, 31); o.pair = r => { const i = Math.floor(r.u() * P.n); return [P.z[2 * i], P.z[2 * i + 1], P.x1[2 * i], P.x1[2 * i + 1]]; }; }
  const tr = M.trainer(p.kind, o);
  while (!tr.done) tr.run(1000);
  weights[name] = M.packNet(tr.params);
  console.log(`${name}: ${STEPS} steps, final loss (EMA) ${tr.ema.toFixed(4)}, ${((Date.now() - t0) / 1000).toFixed(0)} s`);
}
const body = '/* Generated by train.cjs — do not edit. Float32 weights, base64, layer order W1 b1 W2 b2 W3 b3 (10→48→48→2). */\n' +
  '(function (w) { w.NOISE_WEIGHTS = ' + JSON.stringify(weights, null, 1) + '; }(typeof window !== "undefined" ? window : (typeof globalThis !== "undefined" ? globalThis : this)));\n' +
  'if (typeof module === "object" && module.exports) module.exports = (typeof window !== "undefined" ? window : globalThis).NOISE_WEIGHTS;\n';
fs.writeFileSync(out, body);
console.log('wrote', out);
