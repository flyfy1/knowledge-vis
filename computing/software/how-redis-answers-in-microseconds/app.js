/* ───────── chart & collision-safe label helpers ───────── */
function frame(w, h, m, x0, x1, y0, y1) {
  const L = m[3], R = w - m[1], T = m[0], B = h - m[2];
  return { L, R, T, B, X: x => L + (R - L) * (x - x0) / (x1 - x0 || 1), Y: y => B - (B - T) * (y - y0) / (y1 - y0 || 1) };
}
function fitText(c, s, maxW, base, fontTpl) {
  base = base || 12; const tpl = fontTpl || FONT; let fs = base;
  c.font = tpl.replace(/^\d+px/, fs + 'px');
  while (c.measureText(s).width > maxW && fs > 9.5) { fs -= 0.5; c.font = tpl.replace(/^\d+px/, fs + 'px'); }
  return fs;
}
function tryPlace(c, s, x, y, col, align, x0, x1, opts) {
  const o = opts || {};
  const tpl = o.mono ? MONO : FONT;
  const maxW = Math.max(24, (x1 == null ? c.canvas.clientWidth - 4 : x1) - (x0 == null ? 4 : x0));
  const fs = fitText(c, s, maxW, o.fs || 12, tpl);
  const w = c.measureText(s).width;
  const minX = x0 == null ? 4 : x0, maxX = (x1 == null ? c.canvas.clientWidth - 4 : x1) - w;
  let left = align === 'center' ? x - w / 2 : align === 'right' ? x - w : x;
  left = Math.max(minX, Math.min(left, maxX));
  const top = y - fs * 0.55, bot = y + fs * 0.55;
  const placed = c.__placed || (c.__placed = []);
  const pad = o.pad == null ? 3 : o.pad;
  for (const b of placed) {
    if (left < b[2] + pad && left + w > b[0] - pad && top < b[3] + pad && bot > b[1] - pad) {
      if (o.optional) return null;
    }
  }
  placed.push([left, top, left + w, bot]);
  c.fillStyle = col; c.textAlign = 'left';
  c.fillText(s, left, y);
  return { l: left, r: left + w, y };
}
function label(c, s, x, y, col, align, x0, x1, o) { return tryPlace(c, s, x, y, col, align, x0, x1, o); }
function axes(c, f, xLab, yLab) {
  c.strokeStyle = C.line; c.lineWidth = 1; c.beginPath(); c.moveTo(f.L, f.T); c.lineTo(f.L, f.B); c.lineTo(f.R, f.B); c.stroke();
  if (yLab) label(c, yLab, f.L + 4, f.T - 12, C.mute, 'left', f.L, f.R);
  if (xLab) label(c, xLab, f.R, f.B + 28, C.mute, 'right', f.L, f.R);
}
function xTicks(c, f, items) {
  c.font = FONT;
  for (const [x, s] of items) {
    const px = f.X(x);
    if (!tryPlace(c, s, px, f.B + 12, C.mute, 'center', f.L, f.R, { optional: true, pad: 6 })) continue;
    c.strokeStyle = C.line; c.beginPath(); c.moveTo(px, f.B); c.lineTo(px, f.B + 4); c.stroke();
  }
}
function yTicks(c, f, items) {
  c.font = FONT;
  for (const [y, s] of items) {
    const py = f.Y(y);
    if (py < f.T + 2 || py > f.B - 2) continue;
    c.strokeStyle = C.grid; c.beginPath(); c.moveTo(f.L + 1, py); c.lineTo(f.R, py); c.stroke();
    tryPlace(c, s, f.L - 6, py, C.mute, 'right', 2, f.L - 4, { optional: true, pad: 2 });
  }
}
function poly(c, pts, col, lw, dash) {
  c.strokeStyle = col; c.lineWidth = lw || 2; c.lineJoin = 'round'; c.setLineDash(dash || []);
  c.beginPath(); let first = true;
  for (const [x, y] of pts) { if (!isFinite(x) || !isFinite(y)) { first = true; continue; } if (first) c.moveTo(x, y); else c.lineTo(x, y); first = false; }
  c.stroke(); c.setLineDash([]);
}
function dot(c, x, y, col, r) { c.fillStyle = col; c.beginPath(); c.arc(x, y, r || 4.5, 0, 6.283); c.fill(); }
function ring(c, x, y, col, r, lw) { c.strokeStyle = col; c.lineWidth = lw || 1.5; c.beginPath(); c.arc(x, y, r, 0, 6.283); c.stroke(); }

