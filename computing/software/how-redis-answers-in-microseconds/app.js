/* ═════════ ch8: Approx LRU & 8-bit Morris LFU ═════════ */
(function ch8() {
  const cv = $('#c8Cv'), sampS = $('#c8Samp'), hitsS = $('#c8Hits');
  const LRU_CURVE = M.approxLruCurve();
  let samp = 5, fac = 10, hitsExp = 3;
  function update() {
    samp = +sampS.value; hitsExp = +hitsS.value; fac = +radioVal('c8Fac');
    const hits = Math.pow(10, hitsExp);
    const lruErr = LRU_CURVE[samp - 1].errPct;
    const cnt = M.morrisExpectedCounter(hits, fac);
    const prob = M.morrisProb(cnt, fac);
    sliderOut('c8Samp', String(samp));
    sliderOut('c8Hits', M.fmtInt(hits));
    const lruStr = t('u.pct', { v: fmt(lruErr, 1) }), probStr = t('u.pct', { v: fmt(prob * 100, 2) });
    put('#c8Lru', lruStr); put('#c8Saved', '16 MB'); put('#c8Cnt', `${cnt} / 255`); put('#c8Prob', probStr);
    putHTML('#c8Say', t('ch8.say', {
      samp: String(samp), lru: lruStr, saved: '16 MB', fac: String(fac),
      hits: M.fmtInt(hits), cnt: String(cnt), prob: probStr
    }));
    sim.dirty = true;
  }
  const sim = reg(cv, { draw() {
    const { c, w, h } = fit(cv), stacked = w < 540;
    // Left/Top: Approx LRU error curve
    const f1 = stacked
      ? frame(w, h * 0.44, [20, 14, 38, 44], 1, 20, 0, 35)
      : frame(w * 0.48, h, [26, 16, 40, 44], 1, 20, 0, 35);
    yTicks(c, f1, [[0, '0%'], [15, '15%'], [30, '30%']]);
    xTicks(c, f1, [[1, '1'], [5, '5'], [10, '10'], [15, '15'], [20, '20']]);
    axes(c, f1, t('ch8.cv.ax1'), t('ch8.cv.ay1'));
    poly(c, LRU_CURVE.map(p => [f1.X(p.k), f1.Y(p.errPct)]), C.cyan, 2.2);
    dot(c, f1.X(samp), f1.Y(LRU_CURVE[samp - 1].errPct), C.gold, 5);

    // Right/Bottom: Morris 8-bit counter vs log10(hits)
    const f2 = stacked
      ? { L: 44, R: w - 14, T: h * 0.54 + 14, B: h - 40 }
      : { L: w * 0.56 + 34, R: w - 14, T: 26, B: h - 40 };
    f2.X = x => f2.L + (f2.R - f2.L) * (x - 1) / 5;
    f2.Y = y => f2.B - (f2.B - f2.T) * y / 255;
    yTicks(c, f2, [[0, '0'], [128, '128'], [255, '255']]);
    xTicks(c, f2, [[1, '10'], [3, '1k'], [5, '100k'], [6, '1M']]);
    axes(c, f2, t('ch8.cv.ax2'), t('ch8.cv.ay2'));
    for (const fVal of [0, 1, 10, 100]) {
      const pts = [];
      for (let e = 1; e <= 6; e += 0.25) pts.push([f2.X(e), f2.Y(M.morrisExpectedCounter(Math.pow(10, e), fVal))]);
      const active = fVal === fac;
      poly(c, pts, active ? C.gold : 'rgba(163,170,184,.35)', active ? 2.4 : 1.2);
    }
    const curY = M.morrisExpectedCounter(Math.pow(10, hitsExp), fac);
    dot(c, f2.X(hitsExp), f2.Y(curY), C.gold, 5);
  } });
  rangeLab('#c8Samp', update); rangeLab('#c8Hits', update);
  onAll($$('input[name=c8Fac]'), 'change', update);
  langHooks.push(update); update();
})();

