'use strict';
const assert=require('node:assert/strict');
const api=require('../graph-algorithms/app.js');
const g=api.cloneGraph();
assert.deepEqual(api.neighbors(g,'A'),['B','C']);
assert.deepEqual(api.neighbors(g,'B'),['A','C','D']);
const bfs=api.runTraversal(g,'bfs','A');
const dfs=api.runTraversal(g,'dfs','A');
assert.deepEqual(bfs.state.visited,['A','B','C','D','E','F']);
assert.deepEqual(dfs.state.visited,['A','C','E','F','D','B']);
assert.equal(bfs.state.scans,16);
assert.equal(dfs.state.scans,16);
assert.equal(api.complexity(g).V,6);
assert.equal(api.complexity(g).E,8);
assert.equal(api.complexity(g).adjacencyScans,16);
const closed={...g,edges:g.edges.filter(e=>api.neighbors({nodes:g.nodes,edges:[e]},e[0]).length>0)};
assert.equal(api.normalizeGraph({...g,edges:[['A','B'],['B','A'],['A','A'],['A','Z']]}).edges.length,1);
let s=api.initTraversal(g,'bfs','A');
let r=api.traversalStep(s);assert.equal(r.event.node,'A');assert.deepEqual(r.event.found,['B','C']);
r=api.traversalStep(r.state);assert.equal(r.event.node,'B');assert.deepEqual(r.state.container,['C','D']);
console.log('graph-algorithms: all assertions passed');
