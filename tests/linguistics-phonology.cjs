'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..','linguistics-phonology');
for(const file of ['index.html','style.css','i18n.js','app.js','BRIEF.md'])assert.ok(fs.existsSync(path.join(root,file)),`missing ${file}`);
const api=require('../linguistics-phonology/app.js');
assert.equal(api.featureSummary('p').voicing,'voiceless');
assert.equal(api.featureSummary('b').voicing,'voiced');
assert.equal(api.minimalPair('pb').feature,'voicing');
assert.deepEqual(api.syllableSlots('splash'),{onset:'spl',nucleus:'æ',coda:'ʃ',parts:['s','p','l','æ','ʃ']});
assert.deepEqual(api.pluralSurface('voiceless','s'),{rootState:'voiceless',underlying:'s',surface:'s',word:'cats'});
assert.deepEqual(api.pluralSurface('voiceless','z'),{rootState:'voiceless',underlying:'z',surface:'s',word:'cats'});
assert.deepEqual(api.pluralSurface('voiced','s'),{rootState:'voiced',underlying:'s',surface:'z',word:'dogs'});
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
for(const id of ['soundPicker','pairTabs','syllableSlots','rootSelect','suffixSelect','quizOptions'])assert.match(html,new RegExp(`id="${id}"`));
const js=fs.readFileSync(path.join(root,'app.js'),'utf8');
for(const token of ['SOUND_DATA','minimalPair','syllableSlots','pluralSurface','onLangRefresh'])assert.ok(js.includes(token),`missing ${token}`);
const i18n=fs.readFileSync(path.join(root,'i18n.js'),'utf8');
assert.ok(i18n.includes("langchange"));
console.log('linguistics phonology: pure model + structural checks passed');
