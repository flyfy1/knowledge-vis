#!/usr/bin/env node
'use strict';
// Site template (specs/site-template.md): the repo-wide check, the fixture build, the failure modes of
// proposal §8.3, and a converter round trip. Fixture: tests/fixtures/site-template/ (copied to scratch first).
//   node tests/site-template.cjs
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { spawnSync } = require('node:child_process');

const repo = path.resolve(__dirname, '..');
const fixture = path.join(__dirname, 'fixtures', 'site-template');
const base = fs.existsSync('/tmp/agent-tasks') ? '/tmp/agent-tasks' : os.tmpdir();
const scratch = fs.mkdtempSync(path.join(base, 'site-template-test-'));
const PAGE = 'demo/basics/fixture-essay';
let n = 0, modes = 0;
const ok = (cond, msg) => { assert.ok(cond, msg); n++; };

function run(script, ...args) {
  const r = spawnSync('node', [path.join(repo, 'scripts', script), ...args], { encoding: 'utf8' });
  return { code: r.status, out: (r.stdout || '') + (r.stderr || '') };
}
let copies = 0;
function freshSite() { const d = path.join(scratch, 'site' + (++copies)); fs.cpSync(fixture, d, { recursive: true }); return d; }
const pageDir = root => path.join(root, PAGE);
const build = (root, ...flags) => run('build-pages.cjs', pageDir(root), '--root', root, ...flags);
const edit = (root, file, from, to) => {
  const f = path.join(pageDir(root), file), s = fs.readFileSync(f, 'utf8');
  assert.ok(s.includes(from), `fixture ${file} contains ${from}`);
  fs.writeFileSync(f, s.replace(from, to));
};

// 1. The repo: every migrated page matches its sources (today: none, which must pass).
{
  const r = run('build-pages.cjs', '--all', '--check');
  ok(r.code === 0, 'build-pages --all --check passes on the repo:\n' + r.out);
  ok(/PASS: \d+ migrated page/.test(r.out), 'reports the migrated page count');
}

// 2. The fixture builds, and what it builds is right.
const good = freshSite();
{
  const r = build(good);
  ok(r.code === 0, 'fixture builds:\n' + r.out);
  const d = pageDir(good), html = fs.readFileSync(path.join(d, 'index.html'), 'utf8');
  const zh = fs.readFileSync(path.join(d, 'copy.zh.js'), 'utf8'), en = fs.readFileSync(path.join(d, 'copy.en.js'), 'utf8');
  ok(/^<!doctype html>\n<!-- GENERATED by scripts\/build-pages\.cjs/.test(html), 'index.html carries the GENERATED header');
  ok(zh.startsWith('/* GENERATED by scripts/build-pages.cjs from content.zh.md'), 'copy.zh.js carries the GENERATED header');
  ok(en.startsWith('/* GENERATED by scripts/build-pages.cjs from content.en.md'), 'copy.en.js carries the GENERATED header');
  ok(JSON.parse(fs.readFileSync(path.join(d, 'refs.json'), 'utf8'))._generated, 'refs.json marks itself generated');
  ok(html.includes('<html lang="zh-CN" data-template="essay">'), 'migrated pages carry data-template');
  ok(html.includes('<a href="../fixture-target/#ch2">被引用页面第 2 章</a>'), '[[slug#anchor|text]] resolves to a relative link');
  ok(html.includes('<a href="../fixture-target/#ch2">缓存行</a>'), '[[concept:alias]] resolves through the atlas, with the concept title');
  ok(html.includes('<a href="#ch2">下一章</a>'), '[[#anchor|text]] links within the page');
  ok(html.includes('平均寻道 8.5 毫秒，每秒约 79 次'), '{=name} is bound from models.js');
  ok(html.includes('星号本身写成 *。') && html.includes('<strong>加粗</strong>') && html.includes('<em>强调</em>'), 'inline Markdown and escapes');
  ok(html.includes('<text x="100" y="27" text-anchor="middle" data-i18n="dg.stack.top">上层</text>'), 'inline-SVG diagram labels are pre-filled from the diagram block');
  ok(html.includes('aria-label="结构图：上层和下层"'), 'diagram aria-label is pre-filled');
  ok(html.includes('<figure class="dia" data-dg="flow"><div class="svg"></div><figcaption data-i18n-html="dg.flow.cap">图 2'), 'app.js diagram shell keeps its partial');
  ok(/"dg\.flow\.step1": "Seek"/.test(en), 'diagram strings that only app.js uses reach the copy table');
  ok(html.includes('<nav class="site-nav" data-no-autolink data-i18n-aria="site.crumb.aria"'), 'static breadcrumb uses the site-nav markup');
  ok(html.includes('data-crumb="sub" data-i18n="site.crumb.sub">基础</a>'), 'breadcrumb names the subtopic');
  ok(html.includes('<section class="site-xref" id="linked-from" data-no-autolink>') && html.includes('<a href="../fixture-target/#ch1">第 1 章</a> → <a href="#ch2">本页第 2 章</a>'), 'backlinks are generated with chapters');
  ok(/"site\.crumb\.home": "Home"/.test(en), 'chrome strings live in the page copy table');
  ok(html.includes('<link rel="stylesheet" href="../../../site-nav.css?v=') && html.includes('<script defer src="../../../site-nav.js?v='), 'site-nav include lines come from build-site-nav.cjs');
  ok(html.includes('<p class="say" id="fxSay" aria-live="polite"></p>'), 'elements without keys are left empty');
  ok(!/\{=|\[\[/.test(zh + en + html), 'no template syntax leaks into outputs');
  const c = build(good, '--check');
  ok(c.code === 0 && /OK demo\/basics\/fixture-essay/.test(c.out), '--check passes right after a build:\n' + c.out);
}

// 3. Failure modes (proposal §8.3), each exits 1 with a message that names the problem.
function failsWith(label, mutate, re, flags = []) {
  modes++;
  const root = freshSite();
  if (flags.includes('--check')) assert.equal(build(root).code, 0);
  mutate(root);
  const r = build(root, ...flags);
  ok(r.code === 1, `${label}: exits 1 (got ${r.code})\n${r.out}`);
  for (const x of [].concat(re)) ok(x.test(r.out), `${label}: message matches ${x}\n${r.out}`);
}
failsWith('unknown page', r => edit(r, 'content.zh.md', '[[fixture-target#ch2|', '[[fixture-targett#ch2|'), /unknown page "fixture-targett"/);
failsWith('unknown anchor', r => edit(r, 'content.zh.md', '[[fixture-target#ch2|', '[[fixture-target#ch99|'), /page "fixture-target" has no #ch99/);
failsWith('unknown own anchor', r => edit(r, 'content.zh.md', '[[#ch2|', '[[#ch7|'), /page "fixture-essay" has no #ch7/);
failsWith('unbound number', r => edit(r, 'content.zh.md', '{=ch2.seek}', '{=ch2.seeek}'), [/unbound number \{=ch2\.seeek\}/, /binding ch2\.seek is never used/]);
failsWith('number typed over a binding', r => { edit(r, 'content.zh.md', '{=ch2.iops}', '80'); edit(r, 'content.en.md', '{=ch2.iops}', '80'); }, /binding ch2\.iops is never used/);
failsWith('runtime placeholder renamed by a translator', r => edit(r, 'content.en.md', 'Seek {s} ms', 'Seek {sec} ms'), /parity: runtime placeholders differ in ch2\.say\.full/);
failsWith('English ref retargeted', r => edit(r, 'content.en.md', '[[fixture-target#ch2|', '[[fixture-target#ch1|'), /parity: link targets differ in ch1\.p1/);
failsWith('paragraph dropped in translation', r => edit(r, 'content.en.md', 'Where the model stops. {.take}\n', ''), [/parity: zh and en differ in structure/, /parity: en lacks ch2\.limit/]);
failsWith('hand edit of a generated copy file', r => edit(r, 'copy.zh.js', '模型的边界。', '模型的边界（手改）。'), /DRIFT demo\/basics\/fixture-essay: copy\.zh\.js differ/, ['--check']);
failsWith('hand edit of the generated index.html', r => edit(r, 'index.html', '<h2 data-i18n="ch1.title">层次</h2>', '<h2 data-i18n="ch1.title">层次!</h2>'), /DRIFT .*index\.html/, ['--check']);
failsWith('Markdown edited but not rebuilt', r => edit(r, 'content.zh.md', '先看结构。', '先看清结构。'), /DRIFT .*copy\.zh\.js/, ['--check']);
failsWith('concept alias owned twice', r => { edit(r, 'content.zh.md', '[[concept:缓存行]]', '[[concept:重名]]'); edit(r, 'content.en.md', '[[concept:缓存行]]', '[[concept:重名]]'); }, /concept "重名" is ambiguous: fixture-dup-a, fixture-dup-b/);
failsWith('unknown concept', r => edit(r, 'content.zh.md', '[[concept:缓存行]]', '[[concept:没有这个词]]'), /unknown concept "没有这个词"/);
failsWith('partial names a key no block defines', r => edit(r, 'figures/dg-stack.html', 'data-i18n="dg.stack.bottom"', 'data-i18n="dg.stack.middle"'), /figures\/dg-stack\.html names key dg\.stack\.middle/);
failsWith('missing partial', r => edit(r, 'content.zh.md', '::: lab ch2-model', '::: lab ch2-modell'), [/missing partial figures\/ch2-modell\.html/, /parity: zh and en differ in structure/]);
failsWith('paragraph that needs a key', r => edit(r, 'content.zh.md', '一句副标题。<br>第二行。 {.sub}', '一句副标题。<br>第二行。'), /paragraph needs \{#key\}/);

// 4. The converter: a page built without chrome and pre-fill (the old hand-written form) converts back to
//    sources that rebuild it byte for byte, including the inline-SVG diagram.
{
  const root = freshSite(), d = pageDir(root);
  assert.equal(build(root, '--no-chrome', '--no-prefill').code, 0);
  const html = fs.readFileSync(path.join(d, 'index.html'), 'utf8');
  const keep = path.join(scratch, 'original-sources');
  fs.mkdirSync(keep);
  for (const f of ['content.zh.md', 'content.en.md', 'page.json', 'page.css', 'bindings.cjs', 'figures']) fs.renameSync(path.join(d, f), path.join(keep, f));
  const c = run('convert-essay.cjs', d, '--root', root);
  ok(c.code === 0, 'converter round trip on the fixture:\n' + c.out);
  ok(/round trip \(no chrome, no pre-fill\): index\.html byte-identical, copy tables equal in zh and en/.test(c.out), 'converter reports the equivalence proof');
  ok(/1 labs, 2 diagrams/.test(c.out), 'converter finds the lab and both diagram shapes');
  ok(/Derived-From: demo\/basics\/fixture-essay\/copy\.zh\.js -> demo\/basics\/fixture-essay\/content\.zh\.md/.test(c.out), 'converter prints Derived-From trailers');
  const md = fs.readFileSync(path.join(d, 'content.zh.md'), 'utf8');
  ok(md.includes('::: diagram dg-stack keys=dg.stack') && md.includes('\ntop: 上层\n'), 'inline-SVG diagram strings land in a ::: diagram block');
  ok(md.includes('[[fixture-target#ch2|被引用页面第 2 章]]'), 'site links become [[refs]]');
  ok(fs.readFileSync(path.join(d, 'figures', 'dg-stack.html'), 'utf8').includes('<text x="100" y="27" text-anchor="middle" data-i18n="dg.stack.top"></text>'), 'diagram partial is language-neutral');
  const again = build(root, '--no-chrome', '--no-prefill');
  ok(again.code === 0 && fs.readFileSync(path.join(d, 'index.html'), 'utf8') === html, 'converted sources rebuild the same page');
  const twice = run('convert-essay.cjs', d, '--root', root);
  ok(twice.code === 1 && /already has page\.json/.test(twice.out), 'converter refuses an already migrated page');
}

// The scratch copies are removed on success (kept on failure, or with KEEP_SCRATCH=1).
if (!process.env.KEEP_SCRATCH) fs.rmSync(scratch, { recursive: true, force: true });
console.log(`PASS site template: ${n} checks (repo --all --check, fixture build, ${modes} failure modes, converter round trip)`);
