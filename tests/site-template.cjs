// 3. Failure modes (proposal §8.3), each exits 1 with a message that names the problem.
function failsWith(label, mutate, re, flags = []) {
  modes++;
  const root = freshSite();
  if (flags.includes('--check')) assert.equal(build(root).code, 0);
  mutate(root);
  const r = build(root, ...flags);
  ok(r.code === 1, `${label}: exits 1 (got ${r.code})\n${r.out}`);
  for (const x of [].concat(re)) ok(x.test(r.out), `${label}: message matches ${x}\n${r.out}`);
}
