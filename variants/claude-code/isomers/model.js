'use strict';
// Isomers lesson model. Author: Claude Code (claude-opus-5-5), 2026-11-09.
// Carbon skeletons are trees (no rings, at most 4 bonds per carbon). Isomers are counted by exhaustive
// generation with a canonical form, so "same or different" is decided by the model, not by the drawing.
// Boiling points are rounded handbook values (°C, 1 atm). tests/core.cjs pins every claim.
(function (root) {
  /* ---------- trees ---------- */
  // A molecule's heavy-atom graph: { el: ['C', ...], adj: [[...], ...] }.
  function chain(n) { const adj = Array.from({ length: n }, () => []); for (let i = 1; i < n; i++) { adj[i].push(i - 1); adj[i - 1].push(i); } return { el: new Array(n).fill('C'), adj }; }
  // Main chain of length L with alkyl branches [[position (1-based), length], ...].
  function alkane(L, branches = []) {
    const g = chain(L);
    branches.forEach(([pos, len]) => { let prev = pos - 1; for (let k = 0; k < len; k++) { const i = g.el.length; g.el.push('C'); g.adj.push([prev]); g.adj[prev].push(i); prev = i; } });
    return g;
  }
  const clone = g => ({ el: g.el.slice(), adj: g.adj.map(a => a.slice()) });

  // Canonical string of a tree: AHU encoding rooted at the centre (or the smaller of the two centre encodings).
  function centres(g) {
    const n = g.el.length; if (n <= 2) return n === 1 ? [0] : [0, 1];
    const deg = g.adj.map(a => a.length), removed = new Array(n).fill(false);
    let leaves = deg.map((d, i) => (d <= 1 ? i : -1)).filter(i => i >= 0), left = n;
    while (left > 2) {
      const next = [];
      leaves.forEach(l => { removed[l] = true; left--; g.adj[l].forEach(m => { if (!removed[m] && --deg[m] === 1) next.push(m); }); });
      leaves = next;
    }
    return deg.map((d, i) => i).filter(i => !removed[i]);
  }
  function encode(g, v, parent) { const kids = g.adj[v].filter(u => u !== parent).map(u => encode(g, u, v)).sort(); return g.el[v] + '(' + kids.join('') + ')'; }
  function canon(g) { return centres(g).map(c => encode(g, c, -1)).sort()[0]; }

  // Every carbon skeleton with n carbons (degree ≤ 4), generated by adding one carbon to every position.
  const skelCache = { 1: [chain(1)] };
  function skeletons(n) {
    if (skelCache[n]) return skelCache[n];
    const seen = new Map();
    skeletons(n - 1).forEach(g => g.el.forEach((_, v) => {
      if (g.adj[v].length >= 4) return;
      const h = clone(g), i = h.el.length; h.el.push('C'); h.adj.push([v]); h.adj[v].push(i);
      const k = canon(h); if (!seen.has(k)) seen.set(k, h);
    }));
    // stable order: longest chain first, then by canonical string
    return (skelCache[n] = [...seen.values()].sort((a, b) => longestPath(b).length - longestPath(a).length || (canon(a) < canon(b) ? -1 : 1)));
  }

  function dists(g, s) { const d = new Array(g.el.length).fill(-1); d[s] = 0; const q = [s]; while (q.length) { const v = q.shift(); g.adj[v].forEach(u => { if (d[u] < 0) { d[u] = d[v] + 1; q.push(u); } }); } return d; }
  function pathBetween(g, a, b) { const prev = new Array(g.el.length).fill(-1), seen = new Array(g.el.length).fill(false); const q = [a]; seen[a] = true; while (q.length) { const v = q.shift(); g.adj[v].forEach(u => { if (!seen[u]) { seen[u] = true; prev[u] = v; q.push(u); } }); } const p = [b]; while (p[0] !== a) p.unshift(prev[p[0]]); return p; }
  function longestPath(g) {
    const n = g.el.length; if (n === 1) return [0];
    const d0 = dists(g, 0), a = d0.indexOf(Math.max(...d0)), da = dists(g, a), b = da.indexOf(Math.max(...da));
    return pathBetween(g, a, b);
  }
  // Wiener index: sum of bond-count distances over all pairs of carbons (smaller = more compact).
  function wiener(g) { let s = 0; for (let i = 0; i < g.el.length; i++) dists(g, i).forEach((d, j) => { if (j > i) s += d; }); return s; }
  const VALENCE = { C: 4, O: 2 };
  function formula(g) { const c = g.el.filter(e => e === 'C').length, o = g.el.filter(e => e === 'O').length; const h = g.el.reduce((s, e, i) => s + VALENCE[e] - g.adj[i].length, 0); return { C: c, H: h, O: o }; }
  const formulaText = f => `C${f.C > 1 ? f.C : ''}H${f.H}${f.O ? 'O' + (f.O > 1 ? f.O : '') : ''}`.replace(/\d/g, d => '₀₁₂₃₄₅₆₇₈₉'[d]);

  /* ---------- named alkanes with boiling points ---------- */
  const ALKANES = [
    { id: 'butane', g: alkane(4), bp: -0.5 }, { id: 'methylpropane', g: alkane(3, [[2, 1]]), bp: -11.7 },
    { id: 'pentane', g: alkane(5), bp: 36.1 }, { id: 'methylbutane', g: alkane(4, [[2, 1]]), bp: 27.7 }, { id: 'dimethylpropane', g: alkane(3, [[2, 1], [2, 1]]), bp: 9.5 },
    { id: 'hexane', g: alkane(6), bp: 68.7 }, { id: 'm2pentane', g: alkane(5, [[2, 1]]), bp: 60.3 }, { id: 'm3pentane', g: alkane(5, [[3, 1]]), bp: 63.3 },
    { id: 'dm22butane', g: alkane(4, [[2, 1], [2, 1]]), bp: 49.7 }, { id: 'dm23butane', g: alkane(4, [[2, 1], [3, 1]]), bp: 58.0 },
    { id: 'heptane', g: alkane(7), bp: 98.4 }, { id: 'm2hexane', g: alkane(6, [[2, 1]]), bp: 90.0 }, { id: 'm3hexane', g: alkane(6, [[3, 1]]), bp: 92.0 },
    { id: 'e3pentane', g: alkane(5, [[3, 2]]), bp: 93.5 }, { id: 'dm22pentane', g: alkane(5, [[2, 1], [2, 1]]), bp: 79.2 }, { id: 'dm23pentane', g: alkane(5, [[2, 1], [3, 1]]), bp: 89.8 },
    { id: 'dm24pentane', g: alkane(5, [[2, 1], [4, 1]]), bp: 80.5 }, { id: 'dm33pentane', g: alkane(5, [[3, 1], [3, 1]]), bp: 86.1 }, { id: 'tm223butane', g: alkane(4, [[2, 1], [2, 1], [3, 1]]), bp: 80.9 }
  ];
  ALKANES.forEach(a => { a.n = a.g.el.length; a.key = canon(a.g); a.W = wiener(a.g); });
  const byN = n => ALKANES.filter(a => a.n === n);
  const named = g => ALKANES.find(a => a.key === canon(g)) || null;
  // Pairs in one group that follow "smaller W → lower boiling point" (ties in W are skipped).
  function trend(n) { const L = byN(n); let agree = 0, total = 0, against = []; for (let i = 0; i < L.length; i++) for (let j = i + 1; j < L.length; j++) { const dW = L[i].W - L[j].W, dB = L[i].bp - L[j].bp; if (!dW) continue; total++; if (dW * dB > 0) agree++; else against.push([L[i].id, L[j].id]); } return { agree, total, against }; }

  /* ---------- step 1: "same or different" questions ---------- */
  function rng(seed) { let a = seed >>> 0; return () => { a = (a + 0x6D2B79F5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
  const leaves = g => g.el.map((_, i) => i).filter(i => g.adj[i].length <= 1);
  // A drawing = the molecule plus a choice of which leaf-to-leaf path is drawn as the horizontal chain, and mirroring.
  function drawing(g, r) { const L = leaves(g), a = L[Math.floor(r() * L.length)]; let b = a; while (b === a && L.length > 1) b = L[Math.floor(r() * L.length)]; const path = pathBetween(g, a, b), bend = path.length >= 4 && r() < 0.6 ? 1 + Math.floor(r() * (path.length - 2)) : -1;
    return { g, path, bend, flipX: r() < 0.5, flipY: r() < 0.5 }; }
  function question(n, k, seed = 2026) {
    const r = rng(seed * 1000 + n * 100 + k), S = skeletons(n), i = Math.floor(r() * S.length);
    const same = r() < 0.5 || S.length === 1; let j = i; if (!same) while (j === i) j = Math.floor(r() * S.length);
    // What the eye sees: which atoms form the horizontal chain and where it bends (mirror images count as the same look).
    const sig = d => { const L = d.path.length, b = d.bend < 0 ? -1 : Math.min(d.bend, L - 1 - d.bend); return JSON.stringify([d.path.slice().sort((x, y) => x - y), b]); };
    let A = drawing(S[i], r);
    if (same && A.bend < 0 && A.path.length >= 4) A = { ...A, bend: 1 + Math.floor(r() * (A.path.length - 2)) };
    let B = drawing(S[j], r);
    for (let tries = 0; same && sig(B) === sig(A) && tries < 40; tries++) B = drawing(S[j], r); // a "same" pair is drawn two visibly different ways
    return { A, B, same: canon(S[i]) === canon(S[j]) };
  }

  /* ---------- step 4: functional-group isomers ---------- */
  function mol(els, bonds) { const adj = els.map(() => []); bonds.forEach(([a, b]) => { adj[a].push(b); adj[b].push(a); }); return { el: els, adj }; }
  const FUNCTIONAL = [
    { id: 'ethanol', g: mol(['C', 'C', 'O'], [[0, 1], [1, 2]]), bp: 78.4, kind: 'alcohol' },
    { id: 'dme', g: mol(['C', 'O', 'C'], [[0, 1], [1, 2]]), bp: -24.0, kind: 'ether' },
    { id: 'propanol1', g: mol(['C', 'C', 'C', 'O'], [[0, 1], [1, 2], [2, 3]]), bp: 97.2, kind: 'alcohol' },
    { id: 'propanol2', g: mol(['C', 'C', 'C', 'O'], [[0, 1], [1, 2], [1, 3]]), bp: 82.3, kind: 'alcohol' },
    { id: 'mee', g: mol(['C', 'O', 'C', 'C'], [[0, 1], [1, 2], [2, 3]]), bp: 7.4, kind: 'ether' }
  ];
  // O–H groups (an O bonded to fewer than 2 heavy atoms carries H): these can hydrogen-bond.
  const ohCount = g => g.el.reduce((s, e, i) => s + (e === 'O' ? VALENCE.O - g.adj[i].length : 0), 0);

  /* ---------- step 5: rotation about the central bond ---------- */
  // θ = 0: the two end CH₃ groups on the same side (syn / cis). Energies in kJ/mol (teaching fits).
  // Butane: fitted to syn 19, gauche (60°) 3.8, anti 0. 2-Butene: breaking the π bond costs ~265; cis 4 above trans.
  const RT = 8.314462618 * 298.15 / 1000; // 2.48 kJ/mol
  function torsion(kind, deg) {
    const t = deg * Math.PI / 180;
    if (kind === 'single') return 9.5 + 2.5333 * Math.cos(t) + 6.9667 * Math.cos(3 * t);
    return 132.5 * (1 - Math.cos(2 * t)) + 2 * (1 + Math.cos(t));
  }
  const boltz = E => Math.exp(-E / RT);

  const api = { chain, alkane, canon, centres, skeletons, longestPath, pathBetween, wiener, formula, formulaText, ALKANES, byN, named, trend, rng, leaves, drawing, question, FUNCTIONAL, ohCount, RT, torsion, boltz };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else root.ISO_MODEL = api;
})(typeof window !== 'undefined' ? window : globalThis);
