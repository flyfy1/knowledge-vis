#!/usr/bin/env node
/* Site navigation build (specs/site-navigation.md).
 *
 *   node scripts/build-site-nav.cjs            write site-nav-data.js, the <category>/<subtopic>/index.html
 *                                              redirect stubs and the include lines in every live page
 *   node scripts/build-site-nav.cjs --check    fail if any of those three is out of date (no writes)
 *
 * Everything is derived from the site registry (scripts/lib/template.cjs; today it reads pages.config.js:
 * KNOWLEDGE_CATEGORIES, KNOWLEDGE_SUBTOPICS, live KNOWLEDGE_PAGES), so site-nav-data.js is a projection of
 * the same registry the template build uses. Only live pages are touched, so untracked drafts are never edited.
 * Pages built from the site template (a page.json next to index.html) are never written here: their include
 * lines come from the layout, so a stale one is reported with the build-pages command that fixes it.
 *
 * NO_AUTOLINK lists mentions that match a page title exactly but must not become links
 * (for example a book that happens to share a page's title). Each entry is
 * [page path where the mention is, exact title text, reason].
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
// Bump when site-nav.js or site-nav.css change (Cloudflare caches JS/CSS for 4 h, HTML not at all).
const VERSION = 'sn-20261116';
const NO_AUTOLINK = [
];

function loadRegistry() {
  return require('./lib/template.cjs').loadPagesConfig(root);
}
const pick = (v, l) => (v == null ? '' : typeof v === 'string' ? v : (v[l] != null ? v[l] : (v.zh || v.en || '')));

function buildData(w) {
  const cats = {};
  for (const c of w.KNOWLEDGE_CATEGORIES) cats[c.id] = { zh: pick(c.name, 'zh'), en: pick(c.name, 'en') };
  const live = w.KNOWLEDGE_PAGES.filter((p) => p.status === 'live' && p.path);
  const subs = {};
  for (const [cat, list] of Object.entries(w.KNOWLEDGE_SUBTOPICS)) {
    for (const s of list) subs[cat + '/' + s.id] = { zh: pick(s.name, 'zh'), en: pick(s.name, 'en') };
  }
  const pages = live.map((p) => {
    const sub = p.subtopic && subs[p.category + '/' + p.subtopic] ? p.subtopic : '';
    // slug is left empty when it equals the last path segment (all but a few entrance pages).
    const last = p.path.split('/').filter(Boolean).pop();
    return [p.slug === last ? '' : p.slug, p.path, pick(p.title, 'zh'), pick(p.title, 'en'), p.category, sub];
  });
  const usedSubs = {};
  for (const p of pages) if (p[5]) usedSubs[p[4] + '/' + p[5]] = subs[p[4] + '/' + p[5]];
  const noAutolink = NO_AUTOLINK.map((e) => [e[0], e[1]]);
  return { cats, subs: usedSubs, pages, noAutolink };
}

function dataFile(data) {
  return '/* Generated by scripts/build-site-nav.cjs from pages.config.js. Do not edit; run the script. */\n' +
    '/* pages: [slug (empty = last path segment), path, title.zh, title.en, category, subtopic]; noAutolink: [page path, title]. */\n' +
    'window.SITE_NAV_DATA = ' + JSON.stringify(data) + ';\n';
}

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// Same shape as computing/index.html (the category redirect stubs).
function stubFile(cat, sub, catName, subName) {
  const target = '../../?category=' + cat + '&subtopic=' + sub;
  return '<!DOCTYPE html>\n<html lang="zh-CN">\n<head>\n<meta charset="UTF-8">\n<meta name="robots" content="noindex">\n' +
    '<meta http-equiv="refresh" content="0; url=' + esc(target) + '">\n' +
    '<title>' + esc(subName.zh + ' · ' + catName.zh + ' · ' + subName.en + ' · ' + catName.en) + '</title>\n' +
    '<script>location.replace("' + target + '" + location.hash);</script>\n</head>\n' +
    '<body style="background:#0a0e14;color:#e6edf6;font-family:sans-serif;text-align:center;padding-top:20vh;">\n' +
    '<p><a style="color:#67d7f9" href="' + esc(target) + '">' + esc(catName.zh + ' › ' + subName.zh + ' / ' + catName.en + ' › ' + subName.en) + '</a></p>\n' +
    '</body>\n</html>\n';
}

// The two include lines. Depth follows the page path so the files resolve from the site root.
function includeLines(pagePath) {
  const up = '../'.repeat(pagePath.split('/').filter(Boolean).length);
  return {
    link: '<link rel="stylesheet" href="' + up + 'site-nav.css?v=' + VERSION + '">',
    script: '<script defer src="' + up + 'site-nav.js?v=' + VERSION + '"></script>',
  };
}
const LINK_RE = /<link rel="stylesheet" href="(?:\.\.\/)*site-nav\.css(?:\?v=[^"]*)?">/g;
const SCRIPT_RE = /<script defer src="(?:\.\.\/)*site-nav\.js(?:\?v=[^"]*)?"><\/script>/g;

function withInclude(html, pagePath, file) {
  const { link, script } = includeLines(pagePath);
  const nLink = (html.match(LINK_RE) || []).length, nScript = (html.match(SCRIPT_RE) || []).length;
  if (nLink > 1 || nScript > 1) throw new Error(file + ': more than one site-nav include');
  let out = html;
  if (nLink) out = out.replace(LINK_RE, link);
  else {
    const heads = out.match(/<\/head>/gi) || [];
    if (heads.length > 1) throw new Error(file + ': more than one </head>');
    if (heads.length) out = out.replace(/<\/head>/i, link + '\n</head>');
    else {
      // A page without </head> (the head closes implicitly): put it right before <body>.
      if ((out.match(/<body[\s>]/gi) || []).length !== 1) throw new Error(file + ': no unique <body>');
      out = out.replace(/<body([\s>])/i, link + '\n<body$1');
    }
  }
  if (nScript) out = out.replace(SCRIPT_RE, script);
  else {
    const bodies = out.match(/<\/body>/gi) || [];
    if (bodies.length !== 1) throw new Error(file + ': expected exactly one </body>, found ' + bodies.length);
    // Last thing in <body>: deferred, so it runs after the page's own scripts have set html[lang].
    out = out.replace(/<\/body>/i, script + '\n</body>');
  }
  return out;
}

function plan() {
  const w = loadRegistry();
  const data = buildData(w);
  const files = [];
  files.push({ file: 'site-nav-data.js', content: dataFile(data) });
  const catNames = data.cats;
  for (const key of Object.keys(data.subs)) {
    const [cat, sub] = key.split('/');
    files.push({ file: key + '/index.html', content: stubFile(cat, sub, catNames[cat], data.subs[key]), stub: true });
  }
  for (const p of data.pages) {
    const file = p[1] + 'index.html';
    const abs = path.join(root, file);
    if (!fs.existsSync(abs)) throw new Error('live page has no index.html: ' + file);
    const html = fs.readFileSync(abs, 'utf8');
    files.push({ file, content: withInclude(html, p[1], file), page: true, template: fs.existsSync(path.join(root, p[1], 'page.json')) });
  }
  return { data, files };
}

function main() {
  const check = process.argv.includes('--check');
  const { data, files } = plan();
  const stale = [], templateStale = [];
  for (const f of files) {
    const abs = path.join(root, f.file);
    const cur = fs.existsSync(abs) ? fs.readFileSync(abs, 'utf8') : null;
    if (cur === f.content) continue;
    if (f.stub && cur != null && !/<meta name="robots" content="noindex">/.test(cur)) {
      throw new Error(f.file + ' exists and is not a redirect stub; refusing to overwrite');
    }
    if (f.template) { templateStale.push(f.file); continue; }
    stale.push(f.file);
    if (!check) { fs.mkdirSync(path.dirname(abs), { recursive: true }); fs.writeFileSync(abs, f.content); }
  }
  const bytes = Buffer.byteLength(files[0].content);
  const MAX = 60000; // same per-file cap as a search chunk (specs/atlas-search-index.md)
  if (bytes > MAX) { console.error(`site-nav-data.js is ${bytes} bytes, over the ${MAX} byte cap`); process.exit(1); }
  const nStubs = files.filter((f) => f.stub).length, nPages = files.filter((f) => f.page).length;
  if (templateStale.length) {
    console.error('template pages have stale site-nav includes; rebuild them (not edited here):\n' +
      templateStale.map((f) => '  node scripts/build-pages.cjs ' + path.dirname(f)).join('\n'));
    process.exit(1);
  }
  if (check) {
    if (stale.length) {
      console.error('site navigation is out of date; run node scripts/build-site-nav.cjs. Stale:\n  ' + stale.join('\n  '));
      process.exit(1);
    }
    console.log(`PASS: site-nav-data.js (${data.pages.length} pages, ${bytes} bytes), ${nStubs} subtopic stubs, ${nPages} page includes are current`);
  } else {
    console.log(`wrote ${stale.length} file(s): site-nav-data.js ${bytes} bytes, ${nStubs} subtopic stubs, ${nPages} live pages checked`);
  }
}

if (require.main === module) main();
module.exports = { buildData, withInclude, includeLines, stubFile, loadRegistry, VERSION, NO_AUTOLINK };
