#!/usr/bin/env node
'use strict';
// Build the standalone sharded concept search index from atlas/data.js and
// pages.config.js. Independent of scripts/build-atlas-data.cjs so search growth
// never blocks atlas or essay registration. Contract: specs/atlas-search-index.md.
//
//   node scripts/build-search-index.cjs [--check] [--bump-versions]
//   node scripts/build-search-index.cjs --data <atlas/data.js> --out <dir>
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const { execSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const argv = process.argv.slice(2);
let dataArg = null, outArg = null;
const args = new Set();
for (let i = 0; i < argv.length; i++) {
  if (['--data', '--out'].includes(argv[i])) {
    const v = argv[i + 1];
    if (!v) { console.error(`ERROR: ${argv[i]} requires a path argument.`); process.exit(2); }
    if (argv[i] === '--data') dataArg = v; else outArg = v;
    i++;
  } else args.add(argv[i]);
}
if (outArg && (args.has('--check') || args.has('--bump-versions'))) {
  console.error('ERROR: --out cannot be combined with --check or --bump-versions.');
  process.exit(2);
}

const MAX_CHUNK_BYTES = 45000;
const CHUNK_LIMIT = 60000;
const MANIFEST_LIMIT = 30000;

function loadWindowJS(file) {
  const sb = { window: {} };
  vm.runInNewContext(fs.readFileSync(file, 'utf8'), sb);
  return sb.window;
}

const dataFile = dataArg ? path.resolve(dataArg) : path.join(root, 'atlas', 'data.js');
const atlasWin = loadWindowJS(dataFile);
const ATLAS = atlasWin.ATLAS;
if (!ATLAS || !Array.isArray(ATLAS.nodes) || !Array.isArray(ATLAS.groups)) {
  console.error(`ERROR: invalid atlas data in ${dataFile}`);
  process.exit(1);
}

const config = loadWindowJS(path.join(root, 'pages.config.js'));
const pageBySlug = new Map();
for (const p of (config.KNOWLEDGE_PAGES || [])) {
  if (p && p.slug) pageBySlug.set(p.slug, p);
}
const pageByPath = new Map([...pageBySlug.values()].filter(p => p.path).map(p => [p.path, p]));

const atlasRel = 'atlas';
const atlasDir = path.join(root, atlasRel);
function isExternal(href) { return typeof href === 'string' && /^https?:\/\//.test(href); }
function anchorExists(href) {
  if (isExternal(href)) return null;
  const m = typeof href === 'string' && href.match(/^((?:\.\.\/)+(?:[^/#]+\/)*[^/#]+)\/#(.+)$/);
  if (!m) return false;
  const file = path.join(atlasDir, m[1], 'index.html');
  if (!fs.existsSync(file)) return false;
  const html = fs.readFileSync(file, 'utf8');
  if (m[2].startsWith('step')) return html.includes(`id="${m[2]}"`);
  return html.includes(`id="${m[2]}"`) || html.includes(`name="${m[2]}"`);
}
function rootHref(href) {
  if (typeof href !== 'string' || isExternal(href)) return null;
  const [p, hash] = href.split('#');
  let abs = path.posix.normalize(path.posix.join(atlasRel, p));
  if (p.endsWith('/') && !abs.endsWith('/')) abs += '/';
  return abs + (hash && anchorExists(href) !== false ? '#' + hash : '');
}
function bestHref(n) {
  const fromSource = rootHref(n.source);
  if (fromSource && pageByPath.has(fromSource.split('#')[0])) return fromSource;
  const ls = n.lessons || [];
  const l = ls.find(x => x.primary) || ls[0];
  const pg = l && pageBySlug.get(l.slug);
  if (pg && pg.path) return pg.path + (l.anchor ? '#' + l.anchor : (l.step !== null && l.step !== undefined ? '#step' + l.step : ''));
  const lab = ['motion', 'kinematics', 'travel', 'work', 'response']
    .map(id => (ATLAS.trails || []).find(t => t.id === id)).find(t => t && t.nodes.includes(n.id));
  if (lab) return `${atlasRel}/?trail=${lab.id}&node=${encodeURIComponent(n.id)}`;
  return `${atlasRel}/?node=${encodeURIComponent(n.id)}`;
}
function summary(text, lang) {
  if (!text) return '';
  const cap = lang === 'zh' ? 36 : 96;
  const first = (lang === 'zh' ? text.split(/(?<=[。！？])/)[0] : text.split(/(?<=[.!?])\s/)[0]).trim();
  return first.length <= cap ? first : first.slice(0, cap - 1).trimEnd() + '…';
}

const emit = obj => JSON.stringify(obj);
const groups = ATLAS.groups;
const regionIndex = new Map(groups.map((g, i) => [g.id, i]));
const byGroup = new Map(groups.map(g => [g.id, []]));
for (const n of ATLAS.nodes) {
  const rIdx = regionIndex.get(n.group);
  if (rIdx === undefined) { console.error(`ERROR: node ${n.id} has unknown region ${n.group}`); process.exit(1); }
  const row = emit([
    n.id, rIdx, bestHref(n), n.title.zh, n.title.en,
    (n.aliases && n.aliases.zh) || [], (n.aliases && n.aliases.en) || [],
    summary(n.description && n.description.zh, 'zh'), summary(n.description && n.description.en, 'en'),
  ]);
  byGroup.get(n.group).push(row);
}

function renderChunk(gid, rows) {
  return [
    `/* GENERATED by scripts/build-search-index.cjs — do not hand-edit. */`,
    `/* Search index chunk for region "${gid}", loaded lazily by index.html. */`,
    `window.KNOWLEDGE_CONCEPTS.add([`,
    rows.map(r => '  ' + r).join(',\n'),
    `]);`,
  ].join('\n') + '\n';
}

const chunkFiles = new Map(); // filename (e.g. 'math.js') -> content
for (const g of groups) {
  const rows = byGroup.get(g.id) || [];
  if (!rows.length) continue;
  const parts = [];
  let cur = [];
  for (const r of rows) {
    const candidate = renderChunk(g.id, [...cur, r]);
    if (cur.length && Buffer.byteLength(candidate, 'utf8') > MAX_CHUNK_BYTES) {
      parts.push(cur);
      cur = [r];
    } else {
      cur.push(r);
    }
  }
  if (cur.length) parts.push(cur);
  if (parts.length === 1) {
    chunkFiles.set(`${g.id}.js`, renderChunk(g.id, parts[0]));
  } else {
    parts.forEach((p, idx) => chunkFiles.set(`${g.id}-${idx + 1}.js`, renderChunk(`${g.id} (${idx + 1}/${parts.length})`, p)));
  }
}

const chunkRefs = [];
for (const [name, js] of chunkFiles) {
  const hash = crypto.createHash('sha1').update(js).digest('hex').slice(0, 10);
  chunkRefs.push(`search/chunks/${name}?v=${hash}`);
}

const manifestJS = [
  `/* GENERATED by scripts/build-search-index.cjs from ${path.relative(root, dataFile)} — do not hand-edit. */`,
  `/* Sharded concept search manifest for the homepage. Contract: specs/atlas-search-index.md */`,
  `window.KNOWLEDGE_CONCEPTS = {`,
  `  "v": 2,`,
  `  "atlas": ${emit(atlasRel + '/')},`,
  `  "regions": [${groups.map(g => emit([g.id, g.label.zh, g.label.en])).join(', ')}],`,
  `  "fields": ["id","region","href","titleZh","titleEn","aliasesZh","aliasesEn","summaryZh","summaryEn"],`,
  `  "chunks": ${emit(chunkRefs)},`,
  `  "concepts": [],`,
  `  "add": function (rows) { for (var i = 0; i < rows.length; i++) this.concepts.push(rows[i]); }`,
  `};`,
].join('\n') + '\n';

const outDir = outArg ? path.resolve(outArg) : path.join(root, 'search');
const manifestPath = path.join(outDir, 'manifest.js');
const chunksDir = path.join(outDir, 'chunks');

function checkFile(filePath, expected, label) {
  let current;
  try { current = fs.readFileSync(filePath, 'utf8'); } catch (_) { current = null; }
  if (current !== expected) {
    console.log(`DRIFT: generated ${label} differs from committed file.`);
    if (current === null) console.log(`  committed file missing: ${filePath}`);
    else {
      const a = current.split('\n'), b = expected.split('\n');
      for (let i = 0; i < Math.max(a.length, b.length); i++) {
        if (a[i] !== b[i]) {
          console.log(`first diff at line ${i + 1}:\n  committed: ${(a[i] || '').slice(0, 200)}\n  generated: ${(b[i] || '').slice(0, 200)}`);
          break;
        }
      }
    }
    process.exit(1);
  }
}

const staleChunks = () => (fs.existsSync(chunksDir) ? fs.readdirSync(chunksDir) : [])
  .filter(f => f.endsWith('.js') && !chunkFiles.has(f));

if (args.has('--check')) {
  checkFile(manifestPath, manifestJS, path.relative(root, manifestPath));
  for (const [name, js] of chunkFiles) {
    const p = path.join(chunksDir, name);
    checkFile(p, js, path.relative(root, p));
  }
  const stale = staleChunks();
  if (stale.length) {
    console.log(`DRIFT: stale search chunks without a region: ${stale.join(', ')}`);
    process.exit(1);
  }
} else {
  fs.mkdirSync(chunksDir, { recursive: true });
  fs.writeFileSync(manifestPath, manifestJS);
  for (const [name, js] of chunkFiles) fs.writeFileSync(path.join(chunksDir, name), js);
  for (const f of staleChunks()) fs.unlinkSync(path.join(chunksDir, f));
}

const manifestBytes = Buffer.byteLength(manifestJS, 'utf8');
const chunkSizes = [...chunkFiles.entries()].map(([k, v]) => [k, Buffer.byteLength(v, 'utf8')]);
const totalBytes = manifestBytes + chunkSizes.reduce((a, [, b]) => a + b, 0);
const largest = chunkSizes.sort((a, b) => b[1] - a[1])[0] || ['none', 0];
let gateFailed = false;
if (manifestBytes > MANIFEST_LIMIT) {
  console.log(`ERROR: search/manifest.js exceeds the ${MANIFEST_LIMIT}-byte limit (${manifestBytes} bytes).`);
  gateFailed = true;
}
for (const [name, bytes] of chunkSizes) {
  if (bytes > CHUNK_LIMIT) {
    console.log(`ERROR: search/chunks/${name} exceeds the ${CHUNK_LIMIT}-byte limit (${bytes} bytes).`);
    gateFailed = true;
  }
}
console.log(`${args.has('--check') ? 'CHECK OK' : 'WROTE'}: ${ATLAS.nodes.length} concepts across ${chunkFiles.size} chunks (${totalBytes} bytes total; manifest ${manifestBytes} bytes; largest chunk ${largest[0]} ${largest[1]} bytes, limit ${CHUNK_LIMIT}).`);

if (args.has('--bump-versions')) {
  const date = new Date(Date.now() + 8 * 3600 * 1000).toISOString().slice(0, 10).replace(/-/g, '');
  const lastSha = (f) => {
    try { return execSync(`git log -1 --format=%h -- ${f}`, { cwd: root }).toString().trim(); } catch (_) {}
    try { return execSync('git rev-parse --short HEAD', { cwd: root }).toString().trim(); } catch (_) {}
    return '';
  };
  const vManifest = `${date}-${lastSha('search/manifest.js')}`;
  const vMatcher = `${date}-${lastSha('search/concept-search.js')}`;
  const homeFile = path.join(root, 'index.html');
  let home = fs.readFileSync(homeFile, 'utf8');
  home = home.replace(/search\/manifest\.js\?v=[^'"]*/g, `search/manifest.js?v=${vManifest}`)
    .replace(/search\/concept-search\.js\?v=[^'"]*/g, `search/concept-search.js?v=${vMatcher}`);
  fs.writeFileSync(homeFile, home);
  const atlasHtml = path.join(root, 'atlas', 'index.html');
  let atlas = fs.readFileSync(atlasHtml, 'utf8');
  atlas = atlas.replace(/src="\.\.\/search\/concept-search\.js\?v=[^"]*"/g, `src="../search/concept-search.js?v=${vMatcher}"`);
  fs.writeFileSync(atlasHtml, atlas);
  console.log(`BUMPED search cache keys: manifest=${vManifest} matcher=${vMatcher}`);
}

if (gateFailed) process.exit(1);
