'use strict';
const fs=require('fs'),path=require('path');
const root=path.resolve(__dirname,'..');
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const js=fs.readFileSync(path.join(root,'app.js'),'utf8');
const css=fs.readFileSync(path.join(root,'style.css'),'utf8');
const brief=fs.readFileSync(path.join(root,'BRIEF.md'),'utf8');
const spec=fs.readFileSync(path.resolve(root,'../specs/genetics-probability.md'),'utf8');
const cfg=fs.readFileSync(path.join(root,'pages-config-entry.js'),'utf8');
const assert=(x,m)=>{if(!x)throw new Error(m)};
const gametes=g=>{const[a,b]=g.split('');return a===b?[{g:a,p:1}]:[{g:a,p:.5},{g:b,p:.5}]};
const canon=(a,b)=>{if(a===b)return a+b;const u=a.toUpperCase();return (a===u||b===u)?u+u.toLowerCase():u.toLowerCase()+u.toLowerCase()};
const cross=(a,b)=>{const o={AA:0,Aa:0,aa:0};for(const x of gametes(a))for(const y of gametes(b))o[canon(x.g,y.g)]+=x.p*y.p;return o};
const recomb=r=>{const q=r/100;return{AB:(1-q)/2,ab:(1-q)/2,Ab:q/2,aB:q/2}};
const dihybrid=r=>{const p=recomb(r),o={'A_ B_':0,'A_ bb':0,'aa B_':0,'aa bb':0};for(const x of Object.keys(p))for(const y of Object.keys(p)){const A=canon(x[0],y[0]).includes('A')?'A_':'aa',B=canon(x[1],y[1]).includes('B')?'B_':'bb';o[`${A} ${B}`]+=p[x]*p[y]}return o};
assert(html.includes('id="step0"')&&html.includes('id="step4"'),'five-step lesson missing');
['punnettTable','dihybridTable','conditionalTokens','quiz-options','recombination'].forEach(id=>assert(html.includes(`id="${id}"`),`missing interactive ${id}`));
assert(html.includes('data-lang="en"')&&html.includes('data-lang="zh"'),'bilingual toggle missing');
const c=cross('Aa','Aa');assert(Math.abs(c.AA-.25)<1e-9&&Math.abs(c.Aa-.5)<1e-9&&Math.abs(c.aa-.25)<1e-9,'Aa cross must be 1:2:1');
const d=dihybrid(50);assert(Math.abs(d['A_ B_']-9/16)<1e-9&&Math.abs(d['A_ bb']-3/16)<1e-9&&Math.abs(d['aa B_']-3/16)<1e-9&&Math.abs(d['aa bb']-1/16)<1e-9,'independent assortment must be 9:3:3:1');
assert(Math.abs((2/4)/(3/4)-2/3)<1e-9,'P(Aa|A_) must be 2/3');
assert(js.includes('window.GeneticsProbability')&&js.includes('recomb'),'core model not exposed');
assert(css.includes('.causal-flow')&&css.includes('.conditional-token')&&css.includes('.bar-fill'),'causal visuals missing');
assert(brief.includes('分离')&&brief.includes('条件概率')&&spec.includes('重组率'),'teaching docs incomplete');
assert(cfg.includes('genetics-probability')&&cfg.includes('category: "probability"'),'config entry missing');
console.log('genetics-probability core checks passed');
